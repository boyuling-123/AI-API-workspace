/** 从数组里随机取一句，空数组兜底返回空串。 */
function pickRandom(lines: string[]): string {
  if (lines.length === 0) return "";
  return lines[Math.floor(Math.random() * lines.length)];
}

/**
 * 按状态（+ 可选场景）随机取一句台词。
 * 优先取"状态:场景"分组，找不到再回退到通用状态台词。
 */
export function getPetLine(status: PetStatus, scene?: string): string {
  if (scene) {
    const sceneLines = PET_SCENE_LINES[`${status}:${scene}`];
    if (sceneLines && sceneLines.length > 0) return pickRandom(sceneLines);
  }
  return pickRandom(PET_STATUS_LINES[status]);
}

/** 偷溜进中间工作区时的调皮台词。 */
export function getPetMischiefLine(): string {
  return pickRandom(PET_MISCHIEF_LINES);
}

/** 被用户在中间区域点到、逃回空白处时的台词。 */
export function getPetFleeLine(): string {
  return pickRandom(PET_FLEE_LINES);
}
